#!/usr/bin/env python3
"""Regenerates crates/lector-icons assets and src/generated.rs.

Usage:
    scripts/gen_icons.py [MATERIAL_ICON_THEME_DIR] [LUCIDE_STATIC_DIR]

Defaults to /tmp/claude-0/material-icon-theme and /tmp/claude-0/lucide-static
(the unpacked npm packages `material-icon-theme` and `lucide-static`).

* Material Icon Theme (MIT): every icon referenced by dist/material-icons.json
  is copied (minified) to assets/material/, and the file-name / extension /
  folder mappings are emitted as sorted Rust tables (binary searched at runtime).
* Lucide (ISC): every icon named in src/ui.rs (`Variant => "file-stem"`) is
  copied (minified) to assets/lucide/.
"""

import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.join(ROOT, "crates", "lector-icons")
MATERIAL = sys.argv[1] if len(sys.argv) > 1 else "/tmp/claude-0/material-icon-theme"
LUCIDE = sys.argv[2] if len(sys.argv) > 2 else "/tmp/claude-0/lucide-static"


def minify_svg(src: str) -> str:
    src = re.sub(r"<!--.*?-->", "", src, flags=re.S)
    src = re.sub(r"<\?xml.*?\?>", "", src, flags=re.S)
    src = re.sub(r'\sclass="[^"]*"', "", src)
    src = re.sub(r">\s+<", "><", src)
    src = re.sub(r"\s+", " ", src)
    src = re.sub(r"\s*(/?>)", r"\1", src)
    return src.strip() + "\n"


def copy_minified(src_path: str, dst_path: str) -> None:
    with open(src_path, encoding="utf-8") as f:
        data = minify_svg(f.read())
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(data)


def main() -> None:
    with open(os.path.join(MATERIAL, "dist", "material-icons.json"), encoding="utf-8") as f:
        theme = json.load(f)

    definitions = theme["iconDefinitions"]

    def table(mapping: dict, allow_slash: bool = False) -> dict:
        out = {}
        for key, icon in mapping.items():
            k = key.lower()
            if not allow_slash and "/" in k:
                continue
            if icon not in definitions:
                continue
            out.setdefault(k, icon)
        return out

    light = theme.get("light", {})
    tables = {
        "FILE_NAMES": table(theme["fileNames"]),
        "FILE_EXTENSIONS": table(theme["fileExtensions"]),
        "FOLDER_NAMES": table(theme["folderNames"]),
        "FOLDER_NAMES_EXPANDED": table(theme["folderNamesExpanded"]),
        "LIGHT_FILE_NAMES": table(light.get("fileNames", {})),
        "LIGHT_FILE_EXTENSIONS": table(light.get("fileExtensions", {})),
        "LIGHT_FOLDER_NAMES": table(light.get("folderNames", {})),
        "LIGHT_FOLDER_NAMES_EXPANDED": table(light.get("folderNamesExpanded", {})),
    }
    defaults = {
        "DEFAULT_FILE": theme["file"],
        "DEFAULT_FOLDER": theme["folder"],
        "DEFAULT_FOLDER_EXPANDED": theme["folderExpanded"],
        "ROOT_FOLDER": theme["rootFolder"],
        "ROOT_FOLDER_EXPANDED": theme["rootFolderExpanded"],
    }

    used = set(defaults.values())
    for t in tables.values():
        used.update(t.values())
    names = sorted(used)
    index = {n: i for i, n in enumerate(names)}

    material_dir = os.path.join(CRATE, "assets", "material")
    shutil.rmtree(material_dir, ignore_errors=True)
    os.makedirs(material_dir)
    for name in names:
        rel = definitions[name]["iconPath"]
        src = os.path.normpath(os.path.join(MATERIAL, "dist", rel))
        copy_minified(src, os.path.join(material_dir, name + ".svg"))
    shutil.copy(os.path.join(MATERIAL, "LICENSE"), os.path.join(material_dir, "LICENSE"))

    lucide_dir = os.path.join(CRATE, "assets", "lucide")
    # Lector's own icons (`lector-*.svg`, e.g. window caption glyphs) live next to
    # the Lucide ones and are kept; everything else is regenerated.
    os.makedirs(lucide_dir, exist_ok=True)
    for entry in os.listdir(lucide_dir):
        if not entry.startswith("lector-"):
            os.remove(os.path.join(lucide_dir, entry))
    with open(os.path.join(CRATE, "src", "ui.rs"), encoding="utf-8") as f:
        ui_src = f.read()
    lucide_names = re.findall(r'=>\s*"([a-z0-9-]+)",', ui_src)
    for name in lucide_names:
        if name.startswith("lector-"):
            continue
        copy_minified(
            os.path.join(LUCIDE, "icons", name + ".svg"),
            os.path.join(lucide_dir, name + ".svg"),
        )
    shutil.copy(os.path.join(LUCIDE, "LICENSE"), os.path.join(lucide_dir, "LICENSE"))

    out = []
    out.append("// @generated by scripts/gen_icons.py from Material Icon Theme. Do not edit.\n")
    out.append("#![allow(clippy::all)]\n\n")
    out.append("/// Material icon names and SVG bytes, sorted by name.\n")
    out.append("pub(crate) static ICONS: &[(&str, &[u8])] = &[\n")
    for name in names:
        out.append(f'    ("{name}", include_bytes!("../assets/material/{name}.svg")),\n')
    out.append("];\n\n")
    for const, icon in defaults.items():
        out.append(f"pub(crate) const {const}: u16 = {index[icon]}; // {icon}\n")
    out.append("\n")
    for tname, mapping in tables.items():
        out.append(f"pub(crate) static {tname}: &[(&str, u16)] = &[\n")
        for key in sorted(mapping):
            k = key.replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'    ("{k}", {index[mapping[key]]}),\n')
        out.append("];\n\n")
    with open(os.path.join(CRATE, "src", "generated.rs"), "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(f"{len(names)} material icons, {len(lucide_names)} lucide icons")


if __name__ == "__main__":
    main()
