//! Static table of built-in grammars: metadata, query sources, fold hints.

/// Static description of one language.
pub(crate) struct Spec {
    pub name: &'static str,
    pub lsp_id: &'static str,
    pub aliases: &'static [&'static str],
    pub extensions: &'static [&'static str],
    pub file_names: &'static [&'static str],
    pub line_comment: Option<&'static str>,
    pub block_comment: Option<(&'static str, &'static str)>,
    pub grammar: fn() -> tree_sitter::Language,
    /// Highlight query sources, concatenated in order.
    pub highlights: &'static [&'static str],
    pub injections: &'static str,
    pub outline: &'static str,
    /// Tags query sources, concatenated in order.
    pub tags: &'static [&'static str],
    /// Node kinds (in addition to generic heuristics) that can fold.
    pub fold_kinds: &'static [&'static str],
    /// Helper language not listed to users.
    pub hidden: bool,
    /// Definition tags are also derived from outline items (code languages).
    pub outline_symbols: bool,
}

const NONE: &[&str] = &[];

macro_rules! q {
    ($lang:literal, $file:literal) => {
        include_str!(concat!("../queries/", $lang, "/", $file))
    };
}

