    #[test]
    fn concepts_are_parsed_from_toml_and_validated() {
        let text = "[[concept]]\nname = \"cancel token\"\nadr = \"0005\"\nowner = [\"crates/lector-base/**\"]\nstruct = [\"CancelToken\"]\n";
        let parsed = Concept::parse_all(text).expect("parses");
        assert_eq!(parsed.len(), 1);
        assert_eq!(parsed[0].structs, ["CancelToken"]);
        assert!(
            Concept::parse_all("[[concept]]\nname=\"x\"\nadr=\"1\"\nstruct=[\"A\"]\n").is_err()
        );
        assert!(Concept::parse_all("[[concept]]\nname=\"x\"\nadr=\"1\"\nowner=[\"a\"]\n").is_err());
    }
