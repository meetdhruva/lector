    #[test]
    fn fuzzy_modules_and_functions_outside_the_homes() {
        let out = run(
            vec![
                file(
                    "crates/lector-lsp/src/fuzzy.rs",
                    "pub fn score(a: &str) -> u32 { 0 }\npub fn fuzzy_match(q: &str) {}",
                ),
                file(
                    "crates/lector-ui/src/x.rs",
                    "fn rank_fuzzy() {}\nfn fuzzy() {}\nfn unfuzzy_ish() {}\nmod fuzzy { }",
                ),
                file("crates/lector-base/src/fuzzy.rs", "pub fn fuzzy_match() {}"),
                file("crates/lector-search/src/picker.rs", "fn fuzzy_score() {}"),
                file(
                    "crates/lector-search/src/picker/index.rs",
                    "fn fuzzy_score() {}",
                ),
                file("crates/lector-search/src/other.rs", "fn fuzzy_score() {}"),
            ],
            &[fuzzy()],
        );
        let got: Vec<(&str, u32)> = out
            .violations
            .iter()
            .map(|v| (v.file.as_str(), v.line))
            .collect();
        assert_eq!(
            got,
            [
                ("crates/lector-lsp/src/fuzzy.rs", 1),
                ("crates/lector-lsp/src/fuzzy.rs", 2),
                ("crates/lector-search/src/other.rs", 1),
                ("crates/lector-ui/src/x.rs", 1),
                ("crates/lector-ui/src/x.rs", 2),
                ("crates/lector-ui/src/x.rs", 4),
            ]
        );
    }

    #[test]
    fn path_confinement_copies_are_found_by_name_pattern() {
        // The three copies the audit found, matched by name rather than by crate.
        let confine = concept(
            "path confinement",
            &["crates/lector-fs/src/confine.rs"],
            &[],
            &["confine*", "resolve_in_root", "*_in_root"],
            &[],
        );
        let out = run(
            vec![
                file(
                    "crates/lector-fs/src/confine.rs",
                    "pub fn confine(r: &Path, p: &Path) {}",
                ),
                file(
                    "crates/lector-agent/src/paths.rs",
                    "pub fn resolve_in_root(r: &Path, p: &str) {}",
                ),
                file("crates/lector-mcp/src/x.rs", "fn path_in_root(a: &Path) {}"),
                file(
                    "crates/lector-app/src/commands/mod.rs",
                    "impl C { pub fn confine_path(&self) {} }",
                ),
                file(
                    "crates/lector-ui/src/y.rs",
                    "fn unconfined() {}\nfn in_root_ish() {}",
                ),
            ],
            &[confine],
        );
        let files: Vec<&str> = out.violations.iter().map(|v| v.file.as_str()).collect();
        assert_eq!(
            files,
            [
                "crates/lector-agent/src/paths.rs",
                "crates/lector-app/src/commands/mod.rs",
                "crates/lector-mcp/src/x.rs",
            ]
        );
    }

