//! `graph` (ADR 0007): the internal crate dependency diagram, generated and checked.
//!
//! [`render`] produces deterministic text: layers from the top to the bottom (as placed in
//! `arch/layers.toml`), one line per crate with its direct internal dependencies (normal and
//! build; sorted). `arch-check graph --write` puts it between the markers in
//! `docs/ARCHITECTURE.md`; `--check` fails when the committed block differs.

use std::collections::BTreeMap;

use crate::config::Layers;
use crate::meta::Workspace;

/// Marker that opens the generated block.
pub const BEGIN: &str = "<!-- arch-graph:begin -->";
/// Marker that closes the generated block.
pub const END: &str = "<!-- arch-graph:end -->";
/// Heading of the section created when the markers are missing.
pub const HEADING: &str = "## Crate graph (generated)";

const WIDTH: usize = 100;

/// Deterministic text diagram of the internal crate graph.
pub fn render(ws: &Workspace, layers: &Layers) -> String {
    let mut deps: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    let edges = ws.internal_edges();
    for p in &ws.packages {
        deps.entry(p.name.as_str()).or_default();
    }
    for (from, to) in &edges {
        if let Some(v) = deps.get_mut(from.as_str()) {
            v.push(to.as_str());
        }
    }
    let name_width = ws.packages.iter().map(|p| p.name.len()).max().unwrap_or(0);
    let mut out = String::new();
    let mut section = |title: String, crates: Vec<&str>| {
        if crates.is_empty() {
            return;
        }
        out.push_str(&title);
        out.push('\n');
        for c in crates {
            out.push_str(&crate_line(c, &deps[c], name_width));
        }
    };
    for (idx, layer) in layers.layers.iter().enumerate().rev() {
        let mut here: Vec<&str> = layer
            .crates
            .iter()
            .map(String::as_str)
            .filter(|c| deps.contains_key(c))
            .collect();
        here.sort_unstable();
        section(format!("L{idx} {}", layer.name), here);
    }
    let mut unplaced: Vec<&str> = deps
        .keys()
        .copied()
        .filter(|c| layers.layer_of(c).is_none())
        .collect();
    unplaced.sort_unstable();
    section("unplaced (add to arch/layers.toml)".to_string(), unplaced);
    out
}

fn crate_line(name: &str, deps: &[&str], name_width: usize) -> String {
    let prefix = format!("  {name:<name_width$} -> ");
    let indent = " ".repeat(prefix.len());
    if deps.is_empty() {
        return format!("{prefix}(none)\n");
    }
    let mut lines: Vec<String> = Vec::new();
    let mut cur = prefix;
    let mut first = true;
    for (i, d) in deps.iter().enumerate() {
        let piece = if i + 1 < deps.len() {
            format!("{d}, ")
        } else {
            (*d).to_string()
        };
        if !first && cur.len() + piece.trim_end().len() > WIDTH {
            lines.push(cur.trim_end().to_string());
            cur = indent.clone();
        }
        cur.push_str(&piece);
        first = false;
    }
    lines.push(cur.trim_end().to_string());
    let mut s = lines.join("\n");
    s.push('\n');
    s
}

/// The marker-delimited block for `diagram` (no trailing newline).
pub fn block(diagram: &str) -> String {
    format!(
        "{BEGIN}\nGenerated by `scripts/arch-check graph --write` from `cargo metadata` and `arch/layers.toml`; do not edit by hand. CI fails when it differs from the real graph. Layers run from the top (nothing depends on it) to the bottom; a crate depends only on lower layers. Normal and build dependencies between workspace crates only.\n\n```text\n{}```\n{END}",
        diagram
    )
}

/// State of the committed block.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum State {
    /// The block matches the diagram.
    Current,
    /// The block exists and differs.
    Stale,
    /// The markers are missing.
    Missing,
}

fn find_block(doc: &str) -> Option<(usize, usize)> {
    let start = doc.find(BEGIN)?;
    let end = doc[start..].find(END)? + start + END.len();
    Some((start, end))
}

/// Compare the committed block of `doc` with `diagram`.
pub fn check(doc: &str, diagram: &str) -> State {
    let doc = doc.replace("\r\n", "\n");
    match find_block(&doc) {
        None => State::Missing,
        Some((s, e)) if doc[s..e] == block(diagram) => State::Current,
        Some(_) => State::Stale,
    }
}

/// Put the block into `doc`: replace an existing one, or insert a new "Crate graph (generated)"
/// section right after the Principles section. Nothing else in the document changes.
/// Returns an error message when there is neither a block nor a Principles section.
pub fn write_into(doc: &str, diagram: &str) -> Result<String, String> {
    let crlf = doc.contains("\r\n");
    let text = doc.replace("\r\n", "\n");
    let blk = block(diagram);
    let updated = match find_block(&text) {
        Some((s, e)) => format!("{}{}{}", &text[..s], blk, &text[e..]),
        None => {
            let principles = text
                .lines()
                .scan(0usize, |off, l| {
                    let start = *off;
                    *off += l.len() + 1;
                    Some((start, l))
                })
                .find(|(_, l)| l.trim_end() == "## Principles")
                .map(|(s, _)| s)
                .ok_or("docs/ARCHITECTURE.md has no `## Principles` section to insert after")?;
            let after = text[principles..]
                .match_indices("\n## ")
                .next()
                .map(|(i, _)| principles + i + 1);
            let section = format!("{HEADING}\n\n{blk}\n\n");
            match after {
                Some(at) => format!("{}{}{}", &text[..at], section, &text[at..]),
                None => format!("{}\n\n{}", text.trim_end(), section.trim_end()) + "\n",
            }
        }
    };
    Ok(if crlf {
        updated.replace('\n', "\r\n")
    } else {
        updated
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::meta::{DepKind, Package};

    fn layers() -> Layers {
        Layers::parse(
            "[[layer]]\nname=\"low\"\ncrates=[\"a\",\"b\"]\n[[layer]]\nname=\"high\"\ncrates=[\"c\",\"ghost\"]\n",
        )
        .unwrap()
    }

    fn ws() -> Workspace {
        Workspace {
            packages: vec![
                Package::bare("a"),
                Package::bare("b"),
                Package::bare("c")
                    .with_dep("b", DepKind::Normal)
                    .with_dep("a", DepKind::Normal)
                    .with_dep("x", DepKind::Dev),
                Package::bare("stray").with_dep("a", DepKind::Build),
            ],
        }
    }

    #[test]
    fn diagram_is_layered_sorted_and_deterministic() {
        let d = render(&ws(), &layers());
        let expected = "L1 high\n  c     -> a, b\nL0 low\n  a     -> (none)\n  b     -> (none)\nunplaced (add to arch/layers.toml)\n  stray -> a\n";
        assert_eq!(d, expected);
        assert_eq!(d, render(&ws(), &layers()));
    }

    #[test]
    fn long_dependency_lists_wrap() {
        let names: Vec<String> = (0..12)
            .map(|i| format!("lector-long-crate-name-{i}"))
            .collect();
        let mut p = Package::bare("top");
        for n in &names {
            p = p.with_dep(n, DepKind::Normal);
        }
        let mut pkgs = vec![p];
        pkgs.extend(names.iter().map(|n| Package::bare(n)));
        let l = Layers::parse(&format!(
            "[[layer]]\nname=\"low\"\ncrates={:?}\n[[layer]]\nname=\"high\"\ncrates=[\"top\"]\n",
            names
        ))
        .unwrap();
        let d = render(&Workspace { packages: pkgs }, &l);
        assert!(d.lines().all(|l| l.len() <= WIDTH + 30), "{d}");
        assert!(
            d.lines()
                .filter(|l| l.contains("lector-long-crate-name-"))
                .count()
                > 1
        );
    }

    const DOC: &str = "# Title\n\n## Principles\n\n1. one\n2. two\n\n## Write policy\n\ntext\n";

    #[test]
    fn inserts_after_principles_and_nothing_else_changes() {
        let out = write_into(DOC, "L0 x\n").unwrap();
        assert!(out.starts_with("# Title\n\n## Principles\n\n1. one\n2. two\n\n## Crate graph (generated)\n\n<!-- arch-graph:begin -->"));
        assert!(out.ends_with("<!-- arch-graph:end -->\n\n## Write policy\n\ntext\n"));
        assert_eq!(check(&out, "L0 x\n"), State::Current);
        assert_eq!(check(&out, "L0 y\n"), State::Stale);
        assert_eq!(check(DOC, "L0 x\n"), State::Missing);
    }

    #[test]
    fn replaces_an_existing_block_in_place_and_is_idempotent() {
        let once = write_into(DOC, "L0 x\n").unwrap();
        let twice = write_into(&once, "L0 y\n").unwrap();
        assert_eq!(check(&twice, "L0 y\n"), State::Current);
        assert_eq!(write_into(&twice, "L0 y\n").unwrap(), twice);
        assert_eq!(twice.matches(BEGIN).count(), 1);
        assert!(twice.ends_with("\n\n## Write policy\n\ntext\n"));
    }

    #[test]
    fn crlf_documents_stay_crlf() {
        let crlf = DOC.replace('\n', "\r\n");
        let out = write_into(&crlf, "L0 x\n").unwrap();
        assert!(out.contains("\r\n") && !out.replace("\r\n", "").contains('\n'));
        assert_eq!(check(&out, "L0 x\n"), State::Current);
    }

    #[test]
    fn missing_principles_is_an_error() {
        assert!(write_into("# Title\n", "x\n").is_err());
    }
}
